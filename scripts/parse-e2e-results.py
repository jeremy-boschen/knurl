#!/usr/bin/env python3
"""
Parse E2E test results from WebDriver.io JSON output and update status document.

This script reads JSON result files from test-results/ directory and generates
a markdown table showing test pass/fail status.

Usage:
    python3 scripts/parse-e2e-results.py
"""

import json
import glob
from pathlib import Path
from datetime import datetime

# Mapping of test files to expected names
test_mapping = {
    "app.e2e.ts": "Application Smoke Test",
    "auth-tab-activation.e2e.ts": "Auth Tab Activation",
    "auth.e2e.ts": "Authentication Strategies",
    "collection-encryption.e2e.ts": "Collection Encryption & At-Rest Storage",
    "collection-storage.e2e.ts": "Collection Storage & Data Persistence",
    "collections-core.e2e.ts": "Collections Management & Storage",
    "collections-flow.e2e.ts": "Collection And Request Flow",
    "collections-management.e2e.ts": "Collections Management UX",
    "environments.e2e.ts": "Environment Manager Smoke",
    "event-system.e2e.ts": "Event System",
    "import-collection-merge.e2e.ts": "Collection Import from OpenAPI",
    "launch-hydration.e2e.ts": "Launch Hydration UX",
    "tauri-integration.e2e.ts": "Tauri Backend Integration & Desktop Features",
    "workspace-restore.e2e.ts": "Workspace Restore UX",
    "performance.e2e.ts": "Large Collections Performance",
    "request-execution.e2e.ts": "Request Execution & Responses",
    "requests.e2e.ts": "Request Authoring Smoke",
    "settings-ui.e2e.ts": "Settings & UI Customization",
    "tauri-concurrent-invoke.e2e.ts": "Tauri WebDriver Concurrency Bug",
}

def parse_test_results():
    """Parse all JSON result files and return structured data."""
    results_by_file = {}
    result_files = glob.glob('test-results/results-*.json')

    for result_file in result_files:
        try:
            with open(result_file, 'r') as f:
                data = json.load(f)

            if 'specs' in data and data['specs']:
                spec = data['specs'][0]
                # Extract filename from spec path
                filename = spec.split('/')[-1]

                passed = data.get('state', {}).get('passed', 0)
                failed = data.get('state', {}).get('failed', 0)

                if filename in test_mapping:
                    results_by_file[filename] = {
                        'test_name': test_mapping[filename],
                        'passed': passed,
                        'failed': failed,
                        'status': 'PASS' if failed == 0 and passed > 0 else 'FAIL'
                    }
        except json.JSONDecodeError:
            pass  # Skip malformed JSON files
        except Exception as e:
            print(f"Warning: Error parsing {result_file}: {e}")

    return results_by_file

def format_status(filename, results_by_file):
    """Format status badge for a test file."""
    if filename in results_by_file:
        result = results_by_file[filename]
        if result['failed'] > 0:
            return f"❌ FAIL ({result['failed']} failed, {result['passed']} passed)"
        elif result['passed'] > 0:
            return f"✅ PASS ({result['passed']} passed)"
        else:
            return "⚠️ UNKNOWN"
    else:
        return "⏳ NOT RUN"

def generate_markdown_table(results_by_file):
    """Generate markdown table of test results."""
    lines = [
        "# E2E Test Status Inventory\n",
        "This document tracks the pass/fail status of all E2E tests in the codebase.\n",
        f"Last updated: {datetime.now().strftime('%Y-%m-%d %H:%M UTC')}\n",
        "\n## Test Status Table\n",
        "| File Name | Test Name | Status |",
        "|-----------|-----------|--------|",
    ]

    # Sort by filename for consistent output
    for filename in sorted(test_mapping.keys()):
        test_name = test_mapping[filename]
        status = format_status(filename, results_by_file)
        lines.append(f"| {filename} | {test_name} | {status} |")

    lines.extend([
        "\n## Test Status Legend\n",
        "- ✅ PASS: All tests passed",
        "- ❌ FAIL: Some or all tests failed (shows count)",
        "- ⏳ NOT RUN: Test file not yet executed",
        "- ⚠️ UNKNOWN: Results unclear or incomplete data\n",
        "## How to Update This Document\n",
        "Run the status tracker script to refresh results from JSON files:\n",
        "```bash",
        "python3 scripts/parse-e2e-results.py",
        "```\n",
        "This reads test results from `test-results/*.json` files generated by WebDriver.io and updates the status.\n",
        "## Test Results Location\n",
        "JSON results are stored in: `test-results/results-*.json`\n",
        "Each file contains detailed test pass/fail information in WebDriver.io's native JSON format.\n",
        "## Notes\n",
        "- Tests are run individually to identify specific failures",
        "- Status is updated as each test completes",
        "- See `test/specs/` for test implementations",
        "- To run all E2E tests: `yarn test:e2e`",
        "- To run specific test: `yarn test:e2e --spec=\"test/specs/auth.e2e.ts\"`\n",
    ])

    return "\n".join(lines)

def main():
    """Main entry point."""
    results = parse_test_results()
    markdown = generate_markdown_table(results)

    # Write to status document
    status_file = Path("docs/E2E_TEST_STATUS.md")
    status_file.parent.mkdir(parents=True, exist_ok=True)
    status_file.write_text(markdown)

    print(f"Updated {status_file}")
    print("\nStatus Summary:")
    print(markdown)

if __name__ == "__main__":
    main()
